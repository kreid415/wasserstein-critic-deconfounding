"""Table 1 (Pass 27; first author decision: the collapse-rate figure, the former Figure 4, becomes a main-text table). Collapse rate
in percent per penalty, real task and decoder, up to the highest common batch score, with the median over the six real tasks. Every
value is generated from paper/figure_data/collapse_common_range.csv (paper/tools/collapse_common_range.py); nothing is typed.
Writes paper/figure_data/table1_collapse.csv (cond, arm, task, k, n, rate_pct; one row per decoder, penalty and real task, plus a
"median" row per decoder and penalty) and paper/table1.tex (input by paper/outline.tex). Run from the repository root:
python paper/tools/make_table1.py"""
import json

import numpy as np
import pandas as pd

from collapse_common_range import COLLAPSE_BIO, DATA, REAL, ROOT

ARM_LABEL = {"discriminator": "discriminator", "reference": "reference critic", "pooled": "pooled critic",
             "barycenter": "barycenter critic", "mmd": "MMD", "sinkhorn": "Sinkhorn"}
TASK_HEAD = ["pancreas", "lung", r"immune$^\dagger$", "ATAC small", "ATAC large", "human-mouse immune"]  # REAL's order
BLOCKS = [(1, "batch-conditioned decoder"), (0, "unconditioned decoder")]
CAPTION = (r"Collapse rate (percent) of each penalty on the six real tasks, with the batch-conditioned and the unconditioned decoder. "
           rf"A fit collapses when it loses {COLLAPSE_BIO:.2f} or more biology against the same seed's plain scVI with the same decoder. "
           r"Fits are counted at strengths whose mean batch score is at most the highest batch score every penalty reaches. Each cell "
           r"gives the rate and, in parentheses, the collapsed fits over the fits counted; Median is the median of the six rates "
           r"(lower is better). $^\dagger$\,Low-signal pair with the batch-conditioned decoder (the highest common batch score is "
           r"less than 0.02 above plain scVI's; Supplementary Note 5), included in the median. Nominal 95\% intervals and the rates "
           r"over all strengths are in Supplementary Table S8.")


def long_table(cc, low):
    """One row per decoder, penalty and real task (k, n from the common range) and per decoder and penalty a median row."""
    assert low == {("immune", 1)}, low  # the dagger of the immune column
    cc = cc[cc.task.isin(REAL)].set_index(["cond", "arm", "task"])
    rows = []
    for cond, _ in BLOCKS:
        for arm in ARM_LABEL:
            pct = [100 * cc.loc[(cond, arm, t), "rate_common"] for t in REAL]
            rows += [(cond, arm, t, cc.loc[(cond, arm, t), "k_common"], cc.loc[(cond, arm, t), "n_common"], p) for t, p in zip(REAL, pct)]
            rows.append((cond, arm, "median", None, None, float(np.median(pct))))
    return pd.DataFrame(rows, columns=["cond", "arm", "task", "k", "n", "rate_pct"]).astype({"k": "Int64", "n": "Int64"})


def tex(t):
    out = ["% generated by paper/tools/make_table1.py; do not edit", r"\begin{table}[!htbp]", r"\centering\small",
           rf"\caption{{{CAPTION}}}\label{{tab:collapse}}", r"\setlength{\tabcolsep}{4pt}", r"\begin{adjustbox}{max width=\textwidth}\begin{tabular}{@{}lccccccc@{}}", r"\toprule",
           " & ".join(["Penalty"] + TASK_HEAD + ["Median"]) + r" \\"]
    for cond, name in BLOCKS:
        out += [r"\midrule", rf"\multicolumn{{8}}{{@{{}}l}}{{\textit{{{name}}}}} \\"]
        for arm, label in ARM_LABEL.items():
            d = t[(t.cond == cond) & (t.arm == arm)].set_index("task")
            cells = [f"{round(float(d.rate_pct[task])):d} ({d.k[task]}/{d.n[task]})" for task in REAL]
            out.append(" & ".join([label] + cells + [f"{d.rate_pct['median']:.1f}"]) + r" \\")
    return "\n".join(out + [r"\bottomrule", r"\end{tabular}\end{adjustbox}", r"\end{table}", ""])  # adjustbox as in Table S10: never wider than the text


def main():
    pn = json.load(open(DATA / "paper_numbers.json"))
    low = {(t, c) for c in (0, 1) for t in pn[f"low_signal_tasks.cond{c}"]["value"] if t in REAL}
    t = long_table(pd.read_csv(DATA / "collapse_common_range.csv"), low)
    t.to_csv(DATA / "table1_collapse.csv", index=False, float_format="%.6f")
    (ROOT / "paper/table1.tex").write_text(tex(t))
    print(f"wrote {len(t)} rows to paper/figure_data/table1_collapse.csv and paper/table1.tex")


if __name__ == "__main__":  # pragma: no cover  # command-line entry; the functions are tested
    main()
