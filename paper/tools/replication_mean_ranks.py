"""Mean rank over the ranked real tasks on the replication's new seeds (Pass 23), beside the sweep's, per decoder and penalty.
Reads the rank column of paper/supp/tableS9.tex ("replication (sweep)"; generated by paper/tools/make_replication.py from the
agreement result at commit a475ea3); the two simulations are left out, as in the paper's mean ranks.
Writes paper/figure_data/replication_mean_ranks.json.  Run from the repository root:  python paper/tools/replication_mean_ranks.py"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "paper/figure_data/replication_mean_ranks.json"
ARM = {"JS discriminator": "discriminator", "Reference critic": "reference", "Pooled critic": "pooled",
       "Barycenter critic": "barycenter", "MMD": "mmd", "Sinkhorn": "sinkhorn"}
DECODER = {"batch-conditioned": "batch_conditioned", "unconditioned": "unconditioned"}
BLOCK = re.compile(r"\\textit\{([^,]+), (batch-conditioned|unconditioned) decoder;")
ROW = re.compile(r"^([A-Za-z ]+?) &(?: [^&]* &){5} ([\d.]+) \(([\d.]+)\) &")


def ranks(tex):
    """{decoder: {arm: {"replication": [...], "sweep": [...]}}} over the real tasks of Table S9."""
    out, block = {}, None
    for line in tex.splitlines():
        if m := BLOCK.search(line):
            block = None if m.group(1).startswith("Simulation") else DECODER[m.group(2)]
        elif block and (m := ROW.match(line)):
            r = out.setdefault(block, {}).setdefault(ARM[m.group(1).strip()], {"replication": [], "sweep": []})
            r["replication"].append(float(m.group(2)))
            r["sweep"].append(float(m.group(3)))
    return out


def summary(tex):
    res = {}
    for dec, arms in ranks(tex).items():
        n = {len(v["replication"]) for v in arms.values()}
        assert len(arms) == 6 and len(n) == 1, (dec, n)
        res[dec] = {"n_tasks": n.pop(), **{a: {k: round(sum(v[k]) / len(v[k]), 3) for k in ("replication", "sweep")}
                                          for a, v in arms.items()}}
        order = sorted(arms, key=lambda a: res[dec][a]["replication"])
        res[dec]["replication_first"], res[dec]["replication_second"] = order[0], order[1]
    return res


if __name__ == "__main__":
    res = summary((ROOT / "paper/supp/tableS9.tex").read_text())
    OUT.write_text(json.dumps(res, indent=1) + "\n")
    print(json.dumps(res))
