import os
from pathlib import Path

ROOT = Path(os.environ.get("PASS15_ROOT") or Path(__file__).resolve().parents[2])


def edit(path, pairs):
    p = ROOT / path
    s = p.read_text()
    for old, new in pairs:
        assert s.count(old) == 1, (path, s.count(old), old[:100])
        s = s.replace(old, new)
    p.write_text(s)


def rep(new, old):
    return r"\replaced[id=P15]{" + new + "}{" + old + "}"


def swap(old, new, before="", after=""):
    """(before+old+after, before+tracked replacement+after): context makes the old text unique without being changed."""
    return before + old + after, before + rep(new, old) + after


