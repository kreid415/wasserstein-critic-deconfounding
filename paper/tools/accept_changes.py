"""Write the clean copy of the paper: paper/outline.tex with every tracked change of the `changes` package accepted.

Usage, from the repository root:  python paper/tools/accept_changes.py [--src paper/outline.tex] [--out paper/outline_clean.tex] [--check]
Build the clean PDF with  tectonic -X compile paper/outline_clean.tex  (same refs.bib, figures/ and supp/ as outline.tex).

Why a script: \\usepackage[final]{changes} stops with an xkeyval error ("Use of \\XKV@resa doesn't match its definition") on the
nested \\replaced of the writer's-outline header (outline.tex line 48), so the clean text is made here instead.
Method: the preamble (everything before \\begin{document}) is copied unchanged. After it, \\added[..]{x} -> x, \\replaced[..]{new}{old}
-> new (markup inside `new` is accepted too), \\deleted[..]{x} and \\droppeditem{x} -> nothing; TeX comments are copied verbatim and
their braces are not counted; an \\item left with no text (or only a TeX comment) before the next \\item or \\end{..}, a list left with no
\\item and a \\pp{}{} heading left with no text are removed. Exit 1 if any markup is
left outside comments, or (with --check) if --out differs from what the script writes. outline_clean.tex is never edited by hand.
"""
import argparse, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CMD = re.compile(r"\\(added|deleted|replaced|droppeditem)(\[[^\]]*\])?(?=\{)")
HEADER = "% GENERATED by paper/tools/accept_changes.py from paper/outline.tex (tracked changes accepted). Do not edit by hand.\n"


def comment_end(s, i):
    """Index just past the end of the TeX comment that starts at s[i] == '%' (the newline is kept in the comment)."""
    j = s.find("\n", i)
    return len(s) if j < 0 else j + 1


def group(s, i):
    """Return (content, index after the closing brace) of the brace group that starts at s[i]; comments are skipped."""
    if s[i] != "{":
        raise ValueError(f"expected '{{' at {i}: {s[i:i + 40]!r}")
    depth, j = 0, i
    while j < len(s):
        ch = s[j]
        if ch == "\\":
            j += 2
            continue
        if ch == "%":
            j = comment_end(s, j)
            continue
        depth += ch == "{"
        depth -= ch == "}"
        j += 1
        if depth == 0:
            return s[i + 1:j - 1], j
    raise ValueError(f"unbalanced brace group at {i}: {s[i:i + 40]!r}")


def accept(s):
    out, i = [], 0
    while i < len(s):
        if s[i] == "\\":
            m = CMD.match(s, i)
            if m:
                a, j = group(s, m.end())
                if m.group(1) == "replaced":
                    _, j = group(s, j)
                if m.group(1) in ("added", "replaced"):
                    out.append(accept(a))
                i = j
            else:
                out.append(s[i:i + 2])
                i += 2
        elif s[i] == "%":
            j = comment_end(s, i)
            out.append(s[i:j])
            i = j
        else:
            out.append(s[i])
            i += 1
    return "".join(out)


def leftover(body):
    """Markup commands left outside comments (should be none)."""
    code = re.sub(r"(?m)(?<!\\)%.*$", "", body)
    return re.findall(r"\\(?:added|deleted|replaced|droppeditem)\b[^\n]{0,30}", code)  # also malformed uses


def clean(tex):
    head, sep, body = tex.partition("\\begin{document}")
    if not sep:
        raise ValueError("no \\begin{document}")
    body = accept(body)
    body = re.sub(r"\\item(?:\s|%[^\n]*\n)*(?=\\item\b|\\end\{)", "", body)  # bullets left with no text (or only a comment)
    body = re.sub(r"\\begin\{(itemize|enumerate)\}(\[[^\]]*\])?\s*\\end\{\1\}\n?", "", body)  # lists left with no bullet
    body = re.sub(r"\\pp\{\}\{\}\n?", "", body)  # paragraph headings whose title and lead were both deleted
    left = leftover(body)
    if left:
        raise ValueError(f"tracked-change markup left after accepting: {left[:5]}")
    return HEADER + head + sep + body


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", default=str(ROOT / "paper/outline.tex"))
    ap.add_argument("--out", default=str(ROOT / "paper/outline_clean.tex"))
    ap.add_argument("--check", action="store_true", help="exit 1 if --out is not what the script writes")
    a = ap.parse_args(argv)
    text = clean(Path(a.src).read_text())
    out = Path(a.out)
    if a.check:
        ok = out.exists() and out.read_text() == text
        print(f"{out}: {'up to date' if ok else 'DIFFERS from paper/tools/accept_changes.py output'}")
        return int(not ok)
    out.write_text(text)
    print(f"wrote {out} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":  # pragma: no cover  # command-line entry; main() is tested
    sys.exit(main())
